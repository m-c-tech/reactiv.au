const DEFAULT_FRAME_TICKS = 15;

function countFramesFromSource(source) {
  const matches = source.match(/\bROW_LAST\(/g);
  return matches ? matches.length : 0;
}

function makeFrameMeta(frameCount, defaults = {}) {
  return Array.from({ length: frameCount }, () => ({
    mirrorX: false,
    mirrorY: false,
    duration: DEFAULT_FRAME_TICKS,
    ...defaults,
  }));
}

function makeSequenceStep(frameNumber, dur = DEFAULT_FRAME_TICKS, options = {}) {
  return {
    fi: frameNumber - 1,
    dur,
    ...(options.mirrorX ? { mirrorX: true } : {}),
    ...(options.mirrorY ? { mirrorY: true } : {}),
  };
}

function buildDefaultSequence(frameCount, dur = DEFAULT_FRAME_TICKS) {
  return Array.from({ length: frameCount }, (_, index) => makeSequenceStep(index + 1, dur));
}

function appendToolExportMeta(source, meta) {
  const cleanSource = source.replace(/\s*\/\*\s*TOOL_EXPORT_V1[\s\S]*?\*\/\s*$/, '');
  return `${cleanSource}\n\n/* TOOL_EXPORT_V1\n${JSON.stringify(meta)}\n*/`;
}

const EMBEDDED_ANIMATION_OVERRIDES = {
  DNA: {
    frameMeta: (frameCount) => makeFrameMeta(frameCount, { mirrorY: true, duration: DEFAULT_FRAME_TICKS }),
  },
  Heartbeat: {
    frameMeta: (frameCount) => makeFrameMeta(frameCount, { mirrorY: true, duration: 10 }),
    sequence: () => [
      makeSequenceStep(1, 30),
      makeSequenceStep(2, 8),
      makeSequenceStep(3, 8),
      makeSequenceStep(2, 8),
      makeSequenceStep(1, 8),
      makeSequenceStep(2, 8),
    ],
  },
  Skeleton: {
    loopMode: 'pingpong',
    frameMeta: (frameCount) => makeFrameMeta(frameCount, { duration: 20 }),
    sequence: () => [
      makeSequenceStep(1, 40),
      makeSequenceStep(2, 40),
      makeSequenceStep(2, 40, { mirrorX: true }),
      makeSequenceStep(2, 40),
      makeSequenceStep(1, 40),
      makeSequenceStep(2, 40),
      makeSequenceStep(2, 40, { mirrorX: true }),
      makeSequenceStep(1, 40, { mirrorX: true }),
    ],
  },
};

function normalizeEmbeddedAnimation(entry) {
  const frameCount = countFramesFromSource(entry.source);
  const override = EMBEDDED_ANIMATION_OVERRIDES[entry.name] || {};
  const frameMeta = typeof override.frameMeta === 'function'
    ? override.frameMeta(frameCount)
    : makeFrameMeta(frameCount);
  const sequence = typeof override.sequence === 'function'
    ? override.sequence(frameCount)
    : buildDefaultSequence(frameCount, frameMeta[0]?.duration || DEFAULT_FRAME_TICKS);
  const meta = {
    animationName: entry.name,
    loopMode: override.loopMode === 'pingpong' ? 'pingpong' : 'loop',
    frameMeta,
    sequence,
  };
  return {
    name: entry.name,
    file: entry.file,
    source: appendToolExportMeta(entry.source, meta),
  };
}

